export type RecordEnquiryInput = LeadDraft & { idempotencyKey: string }

export async function recordEnquiryAction(
  input: RecordEnquiryInput,
): Promise<ActionResult<{ id: string; attachedToGuest: boolean }>> {
  const gate = await requireReady()
  if (!gate.ok) return gate

  const { context } = gate
  const correlationId = crypto.randomUUID()

  try {
    assertCan(context.actor, 'lead.create', {
      organizationId: context.actor.organizationId,
      propertyId: input.propertyId ?? undefined,
      family: 'booking',
    })

    const supabase = await createClient()
    const { transactions } = transactionRunner(supabase)
    const operations = buildOperations(supabase)

    const outcome = await operations.record.run({
      request: {
        input: {
          source: input.source,
          sourceDetail: orNull(input.sourceDetail),
          propertyId: input.propertyId,
          rawName: orNull(input.rawName),
          rawPhone: orNull(input.rawPhone),
          rawEmail: orNull(input.rawEmail),
          requestedCheckIn: orNull(input.requestedCheckIn),
          requestedCheckOut: orNull(input.requestedCheckOut),
          partyAdults: input.partyAdults,
          partyChildren: input.partyChildren,
          partyInfants: input.partyInfants,
          budgetAgorot: input.budgetAgorot,
          message: orNull(input.message),
        } satisfies LeadDraft,
        idempotencyKey: input.idempotencyKey,
      },
      context: {
        actor: context.actor,
        auditActor: auditActorFor(context.user),
        correlationId,
      },
      services: {
        audit: new SupabaseAuditWriter(supabase),
        events: domainEventBus(supabase),
        idempotency: new SupabaseIdempotencyStore(supabase),
        transactions,
        onEventError(error) {
          console.error('[leads] domain event delivery failed', error)
        },
      },
    })

    revalidatePath('/leads')
    return {
      ok: true,
      data: {
        id: outcome.data.id,
        attachedToGuest: outcome.data.guestId !== null,
      },
    }
  } catch (cause) {
    return { ok: false, error: toSafeResponse(cause, correlationId).error }
  }
}

export type ChangeStatusInput = {
  leadId: string
  status: LeadStatus
  lostReason: LeadLostReason | null
  lostNote: string | null
  bookingId: string | null
  note: string | null
  expectedVersion: number
}

export async function changeEnquiryStatusAction(
  input: ChangeStatusInput,
): Promise<ActionResult<{ id: string }>> {
  const gate = await requireReady()
  if (!gate.ok) return gate

  const { context } = gate
  const correlationId = crypto.randomUUID()

  try {
    assertCan(context.actor, 'lead.update', {
      organizationId: context.actor.organizationId,
      family: 'booking',
    })

    const supabase = await createClient()
    const { transactions } = transactionRunner(supabase)
    const operations = buildOperations(supabase)

    const outcome = await operations.changeStatus.run({
      request: {
        input: {
          leadId: input.leadId,
          status: input.status,
          lostReason: input.lostReason,
          lostNote: orNull(input.lostNote),
          bookingId: input.bookingId,
          note: orNull(input.note),
        },
        resourceId: input.leadId,
        // Optimistic locking, because the board is a screen two people work at
        // once: a card dragged from a stale column would otherwise overwrite a
        // colleague's decision without either of them seeing it.
        expectedVersion: input.expectedVersion,
      },
      context: {
        actor: context.actor,
        auditActor: auditActorFor(context.user),
        correlationId,
        reason: orNull(input.note),
      },
      services: {
        audit: new SupabaseAuditWriter(supabase),
        events: domainEventBus(supabase),
        transactions,
        onEventError(error) {
          console.error('[leads] domain event delivery failed', error)
        },
      },
    })

    revalidatePath('/leads')
    return { ok: true, data: { id: outcome.data.id } }
  } catch (cause) {
    return { ok: false, error: toSafeResponse(cause, correlationId).error }
  }
}

function orNull(value: string | null | undefined): string | null {
  if (value === null || value === undefined) return null
  const trimmed = value.trim()
  return trimmed.length > 0 ? trimmed : null
}

