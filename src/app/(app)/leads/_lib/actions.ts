export type ActionResult<TData> =
  { ok: true; data: TData } | { ok: false; error: SafeErrorBody }

function refusal(
  code: string,
  message: string,
): { ok: false; error: SafeErrorBody } {
  return {
    ok: false,
    error: {
      code,
      message,
      dataMessage: 'הנתונים לא נשמרו. שום דבר במערכת לא השתנה.',
      retryMessage: 'ניסיון חוזר לא יעזור עד שהבעיה תיפתר.',
      dataOutcome: 'not_saved',
      retryable: false,
      correlationId: crypto.randomUUID(),
    },
  }
}

async function requireReady() {
  const context = await shellContext()
  if (!context) {
    return refusal(
      'unauthenticated',
      'החיבור למערכת פג. התחבר מחדש כדי להמשיך.',
    )
  }
  if (context.status !== 'ready') {
    return refusal(
      'membership_not_active',
      'אין לך מרחב עבודה פעיל, ולכן לא ניתן לעבוד עם פניות.',
    )
  }
  return { ok: true as const, context }
}

/* ------------------------------------------------------- what it reads -- */

function buildOperations(db: Db) {
  return defineLeadOperations({
    db,

    async loadLead(organizationId, leadId): Promise<LeadSnapshot | null> {
      const { data, error } = await db
        .from('leads')
        .select(
          'id, property_id, status, version, raw_name, assigned_to_user_id, ' +
            'created_by, first_response_at',
        )
        .eq('organization_id', organizationId)
        .eq('id', leadId)
        .is('deleted_at', null)
        .maybeSingle()

      if (error) throw error
      if (!data) return null

      const row = toRow(data)
      return {
        id: asString(row, 'id'),
        propertyId: asStringOrNull(row, 'property_id'),
        status: asString(row, 'status') as LeadStatus,
        version: asNumber(row, 'version'),
        // Used in the audit sentence. "פנייה ללא שם" and not a made-up name:
        // an enquiry from a number with no name attached is a real thing, and
        // a timeline that invents one is a timeline that cannot be trusted.
        displayName: asStringOrNull(row, 'raw_name') ?? 'פנייה ללא שם',
        assignedToUserId: asStringOrNull(row, 'assigned_to_user_id'),
        createdByUserId: asStringOrNull(row, 'created_by'),
        firstResponseAt: asStringOrNull(row, 'first_response_at'),
      }
    },

    async resolveGuest(organizationId, lead) {
      const phoneE164 = await normalisePhoneInDatabase(db, lead.rawPhone)
      const emailNormalized = normaliseEmailLikeTheColumn(lead.rawEmail)
      if (phoneE164 === null && emailNormalized === null) return null

      // Candidates by either key, then `attachmentFor` decides. Two separate
      // reads rather than one `.or()`: PostgREST's `or` over two columns is
      // easy to get subtly wrong, and being wrong here attaches an enquiry to
      // a stranger.
      const candidates = new Map<string, MatchableGuest>()

      for (const [column, value] of [
        ['phone_e164', phoneE164],
        ['email', emailNormalized],
      ] as const) {
        if (value === null) continue
        const { data, error } = await db
          .from('guests')
          .select('id, full_name, phone_e164, email')
          .eq('organization_id', organizationId)
          .is('deleted_at', null)
          .eq(column, value)
          .limit(10)

        if (error) throw error
        for (const row of toRows(data)) {
          candidates.set(asString(row, 'id'), {
            id: asString(row, 'id'),
            fullName: asStringOrNull(row, 'full_name') ?? '',
            phoneE164: asStringOrNull(row, 'phone_e164'),
            email: asStringOrNull(row, 'email'),
          })
        }
      }

      const attachment = attachmentFor({ phoneE164, emailNormalized }, [
        ...candidates.values(),
      ])
      // Only an exact telephone match attaches. `suggest` is written to the
      // screen for a person, never applied here (ח40-08).
      return attachment.kind === 'attach' ? attachment.guestId : null
    },

    async loadBookingStatus(organizationId, bookingId) {
      const { data, error } = await db
        .from('bookings')
        .select('status')
        .eq('organization_id', organizationId)
        .eq('id', bookingId)
        .is('deleted_at', null)
        .maybeSingle()

      if (error) throw error
      if (!data) return null
      return asString(toRow(data), 'status') as BookingStatusName
    },

    async loadMergeTargets(organizationId, survivorId, mergedId) {
      const { data, error } = await db
        .from('guests')
        .select('id, full_name, version')
        .eq('organization_id', organizationId)
        .in('id', [survivorId, mergedId])

      if (error) throw error
      const rows = toRows(data)
      const survivor = rows.find((row) => asString(row, 'id') === survivorId)
      const merged = rows.find((row) => asString(row, 'id') === mergedId)
      if (!survivor || !merged) return null

      return {
        survivorName: asStringOrNull(survivor, 'full_name') ?? '',
        survivorVersion: asNumber(survivor, 'version'),
        mergedVersion: asNumber(merged, 'version'),
      }
    },
  })
}

/**
 * The database's own normalisation, asked for rather than copied.
 *
 * `normalize_phone_il` is `IMMUTABLE` and granted to `authenticated`, and it
 * is what generated every `phone_e164` in the table this is about to be
 * compared against.
 */
async function normalisePhoneInDatabase(
  db: Db,
  raw: string | null,
): Promise<string | null> {
  if (raw === null || raw.trim().length === 0) return null
  const { data, error } = await db.rpc('normalize_phone_il', { raw })
  if (error) throw error
  return typeof data === 'string' && data.length > 0 ? data : null
}

/** `leads.email_normalized` is `nullif(lower(btrim(raw_email)), '')`. */
function normaliseEmailLikeTheColumn(raw: string | null): string | null {
  if (raw === null) return null
  const trimmed = raw.trim().toLowerCase()
  return trimmed.length > 0 ? trimmed : null
}

