'use server'

/**
 * EXECUTION CONTEXT — SERVER ACTION. Recording an enquiry and moving it along.
 *
 * ── Not one function here writes a row ────────────────────────────────────
 *
 * Each hands the request to an operation in `src/lib/leads`, which is the only
 * path with authorization, validation, the business rule, the transaction, the
 * audit event and idempotency wired in that order. What is left here is the
 * shape of the request and the wiring of the services, exactly as
 * `guests/_lib/actions.ts` does it.
 *
 * ── `assertCan` is called here as well, and that is not belt-and-braces ───
 *
 * `leads_insert` requires `lead.create` at the database and `leads_update`
 * requires `lead.update`, so these checks are not the enforcement. They are the
 * independent one: a Server Action is reachable by a crafted POST whatever the
 * screen rendered, and it must refuse on its own terms before it has read or
 * written anything.
 *
 * ── The telephone number is normalised by the database, never here ────────
 *
 * `resolveGuest` calls `public.normalize_phone_il` over RPC rather than
 * reimplementing it. `guests.phone_e164` and `leads.phone_e164` are both
 * generated by that function, so asking it is the only way to compare like
 * with like — and a second normaliser in TypeScript would be a second answer
 * to "is this the same person", which is the decision this whole module exists
 * to get right. `src/lib/leads/matching.ts` says the same thing at length.
 */

