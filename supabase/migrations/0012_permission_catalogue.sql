-- ============================================================================
-- 3 · The data migration — nobody loses a capability
-- ============================================================================
-- Custom roles only: organization_id IS NOT NULL. A customer composed these
-- for themselves and this file has no business rewriting them, but it does
-- have a duty not to take something away while renaming it.

-- guest.view_contact was phone AND email. Both replacements, to every custom
-- role that held it.
insert into public.role_permissions (role_id, permission_code)
select rp.role_id, replacement.code
from public.role_permissions rp
join public.roles r on r.id = rp.role_id
cross join (values ('guest.view_phone'), ('guest.view_email')) as replacement(code)
where rp.permission_code = 'guest.view_contact'
  and r.organization_id is not null
on conflict do nothing;

-- A name used to be visible to anyone who could read the guest row at all, so
-- guest.view is what actually conferred it. Withholding guest.view_name here
-- would be the same silent loss in a different column.
insert into public.role_permissions (role_id, permission_code)
select rp.role_id, 'guest.view_name'
from public.role_permissions rp
join public.roles r on r.id = rp.role_id
where rp.permission_code = 'guest.view'
  and r.organization_id is not null
on conflict do nothing;

-- Only now is the old grant withdrawn, from custom and system roles alike.
delete from public.role_permissions where permission_code = 'guest.view_contact';


-- ============================================================================
-- 4 · Retire the split grant
-- ============================================================================
-- The foreign key from role_permissions is ON DELETE RESTRICT, so this
-- statement is itself the proof that section 3 left nothing behind: if any
-- role still held it, this would fail rather than orphan a grant.

delete from public.permissions where code = 'guest.view_contact';


-- ============================================================================
-- 5 · Every system role's grant set, as the engine resolves it
-- ============================================================================
-- One block per role: delete what it should no longer hold, insert what it
-- should. Scoped to organization_id IS NULL throughout, so a customer's own
-- roles are never touched.
--
-- organization_owner and administrator keep the derivation 0002 gave them —
-- a query over the catalogue, not a list — so that a permission added
-- tomorrow reaches both without anyone editing this file. What is new is a
-- DELETE beside each, so a grant that should no longer be on the two most
-- senior roles in the product is corrected rather than accumulated.

-- organization_owner and administrator stay derived, exactly as 0002 wrote
-- them and exactly as grantsForSystemRole() computes them: every non-platform
-- permission, minus OWNER_ONLY for the administrator. Re-running the two
-- statements is what carries today's new permissions onto them; the DELETE
-- half is new, so a grant that should no longer be there goes away too.
delete from public.role_permissions rp
 using public.roles r, public.permissions p
 where r.id = rp.role_id
   and p.code = rp.permission_code
   and r.organization_id is null
   and r.code = 'organization_owner'
   and p.is_platform;

insert into public.role_permissions (role_id, permission_code)
select r.id, p.code
from public.roles r
cross join public.permissions p
where r.code = 'organization_owner'
  and r.organization_id is null
  and not p.is_platform
on conflict do nothing;

delete from public.role_permissions rp
 using public.roles r, public.permissions p
 where r.id = rp.role_id
   and p.code = rp.permission_code
   and r.organization_id is null
   and r.code = 'administrator'
   and (p.is_platform or p.is_owner_only);

insert into public.role_permissions (role_id, permission_code)
select r.id, p.code
from public.roles r
cross join public.permissions p
where r.code = 'administrator'
  and r.organization_id is null
  and not p.is_platform
  and not p.is_owner_only
on conflict do nothing;

