   and not (entitlements @> array['agent_network']::text[]);


-- ============================================================================
-- 8 · Drift fails loudly
-- ============================================================================
-- 0002 carried the same guard with the numbers of its day (98 and 7). Updated
-- here, and widened: the two derived roles are checked as well, because their
-- counts are the ones that silently go wrong when a permission is added to the
-- catalogue and the derivation is not re-run — which is exactly the bug this
-- migration exists to repair.

do $$
declare
  action_count integer;
  field_count  integer;
  owner_count  integer;
  admin_count  integer;
begin
  select count(*) into action_count from public.permissions where kind = 'action';
  select count(*) into field_count  from public.permissions where kind = 'field';
  if action_count <> 132 or field_count <> 13 then
    raise exception
      'permission catalogue drift: expected 132 action and 13 field permissions, found % and %',
      action_count, field_count;
  end if;

  select count(*) into owner_count
    from public.role_permissions rp
    join public.roles r on r.id = rp.role_id
   where r.code = 'organization_owner' and r.organization_id is null;

  select count(*) into admin_count
    from public.role_permissions rp
    join public.roles r on r.id = rp.role_id
   where r.code = 'administrator' and r.organization_id is null;

  -- grantsForSystemRole() in src/lib/authz/roles.ts resolves these to 140 and
  -- 136. If the database disagrees, one of the two has moved without the other.
  if owner_count <> 140 or admin_count <> 136 then
    raise exception
      'derived role drift: expected organization_owner 140 and administrator 136, found % and %',
      owner_count, admin_count;
  end if;

  if exists (select 1 from public.permissions where code = 'guest.view_contact') then
    raise exception 'guest.view_contact still exists; the split in section 3 did not complete';
  end if;
end $$;


-- ============================================================================
-- 9 · Commissions get their real gate
-- ============================================================================
-- 0011 gated `commissions` on `finance.view` and said why: the narrower codes
-- existed in permissions.ts but not in the database, and a policy naming a
-- code no role can hold denies everybody. Section 1 has just seeded them, so
-- the provisional gate can go.
--
-- `finance.view` was too wide in both directions. It let an accountant with a
-- read-only remit write a commission row, and it made the agent network's own
-- three-way split — see who is owed, approve it, pay it — invisible to the
-- database. commission.approve and commission.payout are deliberately not held
-- by whoever wrote the commission rule.

drop policy if exists commissions_select on public.commissions;
create policy commissions_select on public.commissions
  for select to authenticated
  using (
    organization_id in (select public.my_organizations())
    and public.property_in_scope(property_id, organization_id)
    and public.has_permission(organization_id, 'commission.view')
  );

drop policy if exists commissions_insert on public.commissions;
create policy commissions_insert on public.commissions
  for insert to authenticated
  with check (
    organization_id in (select public.my_organizations())
    and public.property_in_scope(property_id, organization_id)
    and public.has_permission(organization_id, 'commission.approve')
  );

-- Either grant, because the two acts that move a commission up its ladder are
-- held by different people on purpose: approving what is owed, and paying it.
drop policy if exists commissions_update on public.commissions;
create policy commissions_update on public.commissions
  for update to authenticated
  using (
    organization_id in (select public.my_organizations())
    and public.property_in_scope(property_id, organization_id)
    and (
      public.has_permission(organization_id, 'commission.approve')
      or public.has_permission(organization_id, 'commission.payout')
    )
  )
  with check (
    organization_id in (select public.my_organizations())
    and public.property_in_scope(property_id, organization_id)
    and (
      public.has_permission(organization_id, 'commission.approve')
      or public.has_permission(organization_id, 'commission.payout')
    )
  );
