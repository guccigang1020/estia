-- ============================================================================
-- 0012_permission_catalogue.sql — ESTIA · the catalogue catches up with the code
--
-- What this does
--   Reconciles public.permissions, public.roles and public.role_permissions
--   with src/lib/authz/permissions.ts and src/lib/authz/roles.ts, which have
--   moved a long way since 0002 seeded them.
--
--   0002 says the catalogue "must stay identical" to those files. It was not:
--
--       action permissions      98  ->  132
--       field permissions        7  ->   13
--       system roles            16  ->   20   (+ referral_agent, sales_agent,
--                                              senior_agent, agency_manager)
--
-- ── The part that is a security defect and not a tidiness problem ───────────
--
--   `guest.view_contact` was one grant covering a guest's phone and email. It
--   has been split, because the agent network asks a question the single grant
--   could not answer: give an external seller the phone so they can call their
--   own client, and never the email, which is the business's channel for the
--   next stay.
--
--       guest.view_contact  ->  guest.view_phone + guest.view_email
--
--   And a third grant appeared beside them. `guest.view_name` is genuinely new
--   protection: under the old catalogue a name was visible to anyone who could
--   read the row at all, so it was gated by `guest.view` and by nothing else.
--
--   Both facts make this a data migration and not a seed edit. A custom role
--   somebody built in their own organization holds codes this file is changing
--   underneath them, and a role that silently loses a capability during a
--   migration is an integration defect that surfaces as a receptionist who can
--   no longer see a phone number. So, before anything is removed:
--
--     · every custom role holding `guest.view_contact` is granted BOTH
--       `guest.view_phone` and `guest.view_email`;
--     · every custom role holding `guest.view` is granted `guest.view_name`,
--       because that is exactly what it could already see.
--
--   Only then is `guest.view_contact` withdrawn. The order is the migration.
--
-- ── The derived roles ───────────────────────────────────────────────────────
--
--   0002 computes organization_owner and administrator with INSERT … SELECT
--   over the catalogue, so that adding a permission reaches both without
--   anyone editing a list. That is true of the statement, but the statement
--   ran once in 0002 and cannot reach permissions inserted today. The
--   derivation is therefore re-run here, and the assertion at the foot of this
--   file checks the resulting counts against grantsForSystemRole():
--
--       organization_owner  140   (132 actions - 5 platform + 13 fields)
--       administrator       136   (the same, minus the 4 OWNER_ONLY grants)
--
-- ── How the seed below was produced ─────────────────────────────────────────
--
--   Not by hand. The permission rows and every system role's grant set were
--   generated by running permissions.ts and roles.ts and printing what they
--   actually resolve to — including the three ordered ladders roles.ts now
--   composes with (CALENDAR_LEVELS, PRICE_LEVELS, GUEST_DATA_LEVELS), each
--   flattened through grantsForSystemRole() exactly as the engine flattens it.
--   Transcribing 145 codes and 20 grant sets by eye is how a catalogue drifts
--   in the first place.
--
--   Each role block deletes what the role should no longer hold and inserts
--   what it should, so this file is idempotent and also self-correcting: a
--   grant added to a system role by hand is removed the next time it runs.
--   Custom roles are never touched by those blocks — only by the named data
--   migration in section 3.
--
-- Depends on
--   0002_authz.sql (permissions, roles, role_permissions), 0003_plans.sql
--   (plans, and the entitlements CHECK this file widens).
-- ============================================================================

